class InspectionAiProvider(ABC):
    @abstractmethod
    async def generate_summary(
        self, request: InspectionSummaryRequest
    ) -> InspectionSummaryResponse:
        """Generate structured narrative inspection summary."""
        pass

    @abstractmethod
    async def assistant_chat(
        self, request: InspectionAssistantRequest
    ) -> InspectionAssistantResponse:
        """Answer statutory inquiries with grounded citations."""
        pass


class MockInspectionAiProvider(InspectionAiProvider):
    """
    Deterministic statutory fallback engine.
    Ensures 100% offline availability, zero token expenditure, and strict adherence
    to the Legal Metrology (Packaged Commodities) Rules, 2011.
    """

    async def generate_summary(
        self, request: InspectionSummaryRequest
    ) -> InspectionSummaryResponse:
        prod_name = (request.product_name or "Pre-Packaged Commodity").strip()
        verdict = (request.verdict or "REVIEW").upper().strip()

        declarations = request.extracted_declarations or {}
        flagged_rules = list(request.flagged_rules or [])
        potential_violations = list(request.potential_violations or [])
        evidence_snippets = dict(request.evidence_snippets or {})

        key_findings: List[str] = []
        declarations_requiring_attention: List[str] = []
        evidence_explanation: List[str] = []
        applicable_rules: List[str] = []
        recommended_next_steps: List[str] = []

        # 1. Detect conflicting panel values
        has_conflicts = False
        conflict_details: List[str] = []

        # Check violations for conflict keywords
        for viol in potential_violations:
            issue_text = viol.get("issue", "").lower()
            field_name = viol.get("field", "")
            if any(k in issue_text for k in ["conflict", "mismatch", "discrepan", "differ", "contradict", "between panel"]):
                has_conflicts = True
                conflict_details.append(viol.get("issue", "Conflicting panel declarations detected."))
                if field_name and field_name not in declarations_requiring_attention:
                    declarations_requiring_attention.append(field_name)

        # Check evidence snippets for multiple conflicting panels
        if evidence_snippets:
            panel_keys = [k for k in evidence_snippets.keys() if "panel" in k.lower()]
            if len(panel_keys) >= 2:
                # Compare text across panels if snippet mentions weights or quantities
                quantities = {}
                for pk in panel_keys:
                    val = str(evidence_snippets[pk])
                    qm = re.findall(r"(\d+(?:\.\d+)?\s*(?:kg|g|gm|ml|l|grams|litres))", val, re.IGNORECASE)
                    if qm:
                        quantities[pk] = qm[0].lower().replace(" ", "")

                if len(set(quantities.values())) > 1:
                    has_conflicts = True
                    conf_desc = f"Quantity declaration discrepancy between panels: " + ", ".join([f"{k} specifies '{v}'" for k, v in quantities.items()])
                    if conf_desc not in conflict_details:
                        conflict_details.append(conf_desc)
                    if "net_quantity" not in declarations_requiring_attention:
                        declarations_requiring_attention.append("net_quantity")

        if has_conflicts:
            for cd in conflict_details:
                key_findings.append(f"Conflicting panel values: {cd}")
                evidence_explanation.append(
                    f"Multi-panel OCR analysis detected conflicting declarations: {cd}. "
                    f"Under Rule 6, packaging display panels must provide uniform, unambiguous information."
                )
            if "LM-PCR-2011-R6-1-C" not in flagged_rules:
                flagged_rules.append("LM-PCR-2011-R6-1-C")

        # 2. Check missing or flagged declarations
        # MRP
        mrp_val = declarations.get("mrp") or declarations.get("maximum_retail_price")
        if "LM-PCR-2011-R6-1-DA" in flagged_rules or mrp_val is None or (isinstance(mrp_val, str) and not mrp_val.strip()):
            if "mrp" not in declarations_requiring_attention:
                declarations_requiring_attention.append("mrp")
            key_findings.append(
                "Mandatory Maximum Retail Price (MRP) declaration is missing, incomplete, or lacks the statutory 'inclusive of all taxes' clause."
            )
            evidence_explanation.append(
                "Rule 6(1)(da) (G.S.R. 779(E)) requires MRP to be clearly legible and explicitly stated as 'inclusive of all taxes'."
            )
            applicable_rules.append("LM-PCR-2011-R6-1-DA: Maximum Retail Price (MRP) — Rule 6(1)(da), G.S.R. 779(E)")

        # Net Quantity
        net_qty = declarations.get("net_quantity") or declarations.get("netQuantity")
        if "LM-PCR-2011-R6-1-C" in flagged_rules or net_qty is None or (isinstance(net_qty, str) and not net_qty.strip()):
            if "net_quantity" not in declarations_requiring_attention:
                declarations_requiring_attention.append("net_quantity")
            if not any("quantity" in f.lower() for f in key_findings):
                key_findings.append(
                    "Net quantity declaration is missing, ambiguous, or expressed in non-standard units under Second Schedule."
                )
                evidence_explanation.append(
                    "Rule 6(1)(c) read with G.S.R. 202(E) mandates net quantity in terms of standard metric weight (g, kg) or volume (ml, l)."
                )
            applicable_rules.append("LM-PCR-2011-R6-1-C: Net Quantity Declaration — Rule 6(1)(c), G.S.R. 202(E)")

        # Manufacturer / Packer
        mfg = declarations.get("manufacturer") or declarations.get("packer") or declarations.get("importer")
        if "LM-PCR-2011-R6-1-A-NAME" in flagged_rules or mfg is None or (isinstance(mfg, str) and not mfg.strip()):
            if "manufacturer" not in declarations_requiring_attention:
                declarations_requiring_attention.append("manufacturer")
            key_findings.append(
                "Manufacturer, packer, or importer corporate entity declaration is missing or incomplete."
            )
            evidence_explanation.append(
                "Rule 6(1)(a) mandates the explicit name of the manufacturer, packer, or importer."
            )
            applicable_rules.append("LM-PCR-2011-R6-1-A-NAME: Name of Manufacturer/Packer/Importer — Rule 6(1)(a), G.S.R. 202(E)")

        # Address
        addr = declarations.get("address") or declarations.get("premises") or declarations.get("factory")
        if "LM-PCR-2011-R6-1-A-ADDR" in flagged_rules or (addr is None and declarations and "manufacturer" in declarations):
            if "address" not in declarations_requiring_attention:
                declarations_requiring_attention.append("address")
            key_findings.append(
                "Complete postal address or manufacturing premises location is not clearly indicated."
            )
            applicable_rules.append("LM-PCR-2011-R6-1-A-ADDR: Premises/Factory Address — Rule 6(1)(a), G.S.R. 202(E)")

        # Date of Manufacture / Packing
        dt = declarations.get("date_declaration") or declarations.get("packing_date") or declarations.get("mfd") or declarations.get("pkd")
        if "LM-PCR-2011-R6-1-D" in flagged_rules or dt is None or (isinstance(dt, str) and not dt.strip()):
            if "date_declaration" not in declarations_requiring_attention:
                declarations_requiring_attention.append("date_declaration")
            key_findings.append(
                "Month and year of manufacture or pre-packing is missing, post-dated, or lacks statutory prefix."
            )
            evidence_explanation.append(
                "Rule 6(1)(d) (G.S.R. 779(E)) mandates month and year of manufacture/packing (e.g. MM/YYYY or Month YYYY)."
            )
            applicable_rules.append("LM-PCR-2011-R6-1-D: Month & Year of Manufacture/Packing — Rule 6(1)(d), G.S.R. 779(E)")

        # Consumer Care
        care = declarations.get("consumer_care") or declarations.get("consumerCare") or declarations.get("helpline")
        if "LM-PCR-2011-R6-1-E" in flagged_rules or care is None or (isinstance(care, str) and not care.strip()):
            if "consumer_care" not in declarations_requiring_attention:
                declarations_requiring_attention.append("consumer_care")
            key_findings.append(
                "Consumer grievance redressal contact (telephone helpline or email address) not detected."
            )
            evidence_explanation.append(
                "Rule 6(1)(e) (G.S.R. 359(E)) requires name, telephone helpline, and email address for consumer grievance redressal."
            )
            applicable_rules.append("LM-PCR-2011-R6-1-E: Consumer Care Redressal Details — Rule 6(1)(e), G.S.R. 359(E)")

        # Add any other potential violations from request
        for v in potential_violations:
            rule_id = v.get("rule_id")
            issue = v.get("issue")
            field = v.get("field")
            if field and field not in declarations_requiring_attention:
                declarations_requiring_attention.append(field)
            if issue and issue not in key_findings:
                key_findings.append(issue)
            if rule_id and not any(rule_id in ar for ar in applicable_rules):
                applicable_rules.append(f"{rule_id}: Statutory rule requirement under Legal Metrology Rules, 2011")

        # Fallback evidence explanations from evidence_snippets
        if evidence_snippets and not evidence_explanation:
            for panel_name, snippet in evidence_snippets.items():
                evidence_explanation.append(f"Panel '{panel_name}' OCR evidence: '{snippet}'")

        # 3. Finalize synthesis based on PASS or REVIEW
        if verdict == "PASS" and not flagged_rules and not declarations_requiring_attention:
            overall_summary = (
                f"Automated screening for '{prod_name}' did not flag any configured checks in the provided declarations. "
                "This is a screening result, not a legal determination. Confirm the original package and applicable requirements."
            )
            display_names = {
                "mrp": "MRP", "maximum_retail_price": "MRP", "net_quantity": "Net quantity",
                "netQuantity": "Net quantity", "manufacturer": "Manufacturer", "packer": "Packer",
                "address": "Address", "date_declaration": "Date declaration", "packing_date": "Date declaration",
                "consumer_care": "Consumer care", "consumerCare": "Consumer care",
            }
            key_findings = [f"{display_names.get(field, field.replace('_', ' ').title())} text detected: {value}." for field, value in declarations.items() if value]
            if not key_findings:
                key_findings = ["No configured issue was flagged; inspect the extracted declarations and original package."]
            evidence_explanation = ["The provided OCR declarations did not trigger the configured screening checks. Confirm legibility, context, and package details on the original images."]
            applicable_rules = [
                "Rule 6(1)(a)-(g), Legal Metrology (Packaged Commodities) Rules, 2011",
                "G.S.R. 202(E) read with G.S.R. 779(E) (Ministry of Consumer Affairs)",
            ]
            recommended_next_steps = [
                "Review the extracted values against the original package before relying on this screening result.",
                "Check current applicable requirements and any declarations that were not readable in the scanned images.",
            ]
        else:
            verdict = "REVIEW"
            count = len(declarations_requiring_attention) or len(flagged_rules) or 1
            overall_summary = (
                f"Automated statutory screening for '{prod_name}' evaluated to REVIEW. The deterministic rule engine "
                f"flagged {count} statutory declaration(s) requiring inspector attention under the Legal Metrology "
                f"(Packaged Commodities) Rules, 2011. The package cannot be certified compliant without physical verification or human review."
            )
            if not key_findings:
                key_findings.append(f"Statutory rule check flagged {count} potential non-compliance issue(s).")
            if not evidence_explanation:
                evidence_explanation.append("Packaging label OCR inspection detected missing or non-conforming mandatory declarations.")
            if not applicable_rules:
                applicable_rules.append("Legal Metrology (Packaged Commodities) Rules, 2011 (Rule 6)")

            applicable_rules.append("Section 36, Legal Metrology Act, 2009 — Penalty for non-standard packages")

            recommended_next_steps = [
                "Inspect physical product package directly to verify whether flagged declarations are present on un-scanned panels or curved label areas.",
                "If declarations are legible on the physical sample, use the Human Review workspace to transcribe them and re-run deterministic screening.",
            ]
            if has_conflicts or "net_quantity" in declarations_requiring_attention:
                recommended_next_steps.insert(
                    0,
                    "Perform gravimetric physical verification using a calibrated laboratory balance to determine actual net contents against Second Schedule tolerance limits.",
                )
            if "mrp" in declarations_requiring_attention:
                recommended_next_steps.append(
                    "Verify retail point-of-sale scanning price against declared label price to check for unauthorized overcharging.",
                )
            recommended_next_steps.append(
                "If non-compliance is physically corroborated, issue statutory notice under Section 36 of the Legal Metrology Act, 2009.",
            )

        # Deduplicate while preserving order
        declarations_requiring_attention = list(dict.fromkeys(declarations_requiring_attention))
        applicable_rules = list(dict.fromkeys(applicable_rules))
        recommended_next_steps = list(dict.fromkeys(recommended_next_steps))

        return InspectionSummaryResponse(
            overall_summary=overall_summary,
            key_findings=key_findings,
            declarations_requiring_attention=declarations_requiring_attention,
            evidence_explanation=evidence_explanation,
            applicable_rules=applicable_rules,
            recommended_next_steps=recommended_next_steps,
            is_ai_generated=False,
            provider_used="mock-statutory-engine",
            disclaimer=STATUTORY_DISCLAIMER,
        )

    async def assistant_chat(
        self, request: InspectionAssistantRequest
    ) -> InspectionAssistantResponse:
        q = request.query.lower().strip()
        matched_rules = []
        citations = []

        # 1. Guardrail against overriding compliance verdicts
        if any(w in q for w in ["override", "make it pass", "mark pass", "force pass", "change verdict", "alter verdict", "declare compliant", "clear compliance"]):
            return InspectionAssistantResponse(
                answer=(
                    "Under Section 36 of the Legal Metrology Act, 2009 and the LMCC architecture, compliance "
                    "verdicts are strictly deterministic. The AI Inspection Assistant cannot manually override or alter "
                    "an inspection verdict to 'PASS'. If a declaration is missing, ambiguous, or conflicting, you must "
                    "perform physical verification or use the Human Review workflow to correct verified visual misreadings."
                ),
                citations=[
                    GroundedCitation(
                        rule_id="LM-ACT-2009-S36",
                        clause="Section 36, Legal Metrology Act, 2009",
                        title="Penalty for Non-Standard Packages",
                        gazette_reference="Act No. 1 of 2010 (Ministry of Consumer Affairs)",
                        summary="Mandates penalties for manufacture, packing, sale, or distribution of non-conforming pre-packaged commodities.",
                    )
                ],
                suggested_followups=[
                    "What are the statutory penalties for non-standard packages under Section 36?",
                    "How do I use Human Review to transcribe an obscured declaration?",
                    "Which mandatory declarations are currently flagged?",
                ],
                is_ai_generated=False,
                is_offline_fallback=True,
                provider_used="mock-statutory-engine (guardrail)",
                disclaimer=STATUTORY_DISCLAIMER,
                legal_disclaimer=STATUTORY_DISCLAIMER,
            )

        # 2. Check flagged rules context
        if request.flagged_rules:
            for rid in request.flagged_rules:
                r = get_rule_by_id(rid)
                if r and r not in matched_rules:
                    matched_rules.append(r)

        # 3. Keyword matching across statutory declarations
        if any(w in q for w in ["mrp", "price", "retail", "tax", "inclusive", "overcharging"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-DA")
            if r and r not in matched_rules:
                matched_rules.append(r)
        if any(w in q for w in ["quantity", "net qty", "weight", "volume", "standard unit", "grams", "litres", "piece"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-C")
            if r and r not in matched_rules:
                matched_rules.append(r)
        if any(w in q for w in ["manufacturer", "packer", "importer", "brand", "company"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-A-NAME")
            if r and r not in matched_rules:
                matched_rules.append(r)
        if any(w in q for w in ["address", "factory", "premises", "pin code", "postal"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-A-ADDR")
            if r and r not in matched_rules:
                matched_rules.append(r)
        if any(w in q for w in ["date", "mfd", "pkd", "month", "year", "post-dated", "expiry"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-D")
            if r and r not in matched_rules:
                matched_rules.append(r)
        if any(w in q for w in ["consumer care", "helpline", "email", "customer care", "complaint", "redressal"]):
            r = get_rule_by_id("LM-PCR-2011-R6-1-E")
            if r and r not in matched_rules:
                matched_rules.append(r)

        if not matched_rules:
            matched_rules = STATUTORY_RULES_CORPUS[:3]

        for r in matched_rules:
            citations.append(
                GroundedCitation(
                    rule_id=r.id,
                    clause=r.source,
                    title=r.title,
                    gazette_reference=r.gazetteReference,
                    summary=r.description,
                )
            )

        # Narrative response sections
        sections = []
        if request.verdict:
            verdict_text = f"**Current Inspection State:** Evaluated as `{request.verdict}`."
            if request.flagged_rules:
                verdict_text += f" Flagged statutory rule(s): {', '.join(request.flagged_rules)}."
            sections.append(verdict_text)

        if any(w in q for w in ["why", "flag", "reason", "issue", "violation"]):
            reasons = []
            for r in matched_rules:
                reasons.append(
                    f"• **{r.title} ({r.source})**: Under {r.gazetteReference}, {r.description.lower()} "
                    f"**Detection scope:** {r.whatCanBeDetected} **Legal Limitation:** {r.legalLimitations}"
                )
            sections.append("**Statutory Analysis & Why It Was Flagged:**\n" + "\n".join(reasons))
            followups = [
                "What physical checks should the inspector conduct?",
                "How do I correct an OCR misreading using Human Review?",
                "What is the statutory penalty under Section 36?",
            ]
        elif any(w in q for w in ["physical", "field check", "inspect", "scale"]):
            sections.append(
                "**Inspector Physical Verification Protocol:**\n"
                "1. **Net Quantity Check**: Calibrated laboratory balance verification as per Second Schedule tolerances.\n"
                "2. **Point of Sale Pricing**: Verify actual scanning price against declared MRP (overcharging check).\n"
                "3. **Address Verification**: Confirm physical existence of registered premises or factory.\n"
                "4. **Consumer Redressal Test**: Dial declared helpline or transmit verification email to ensure responsiveness."
            )
            followups = [
                "What are the permissible maximum error limits for net quantity?",
                "Can unit sale price be declared instead of MRP?",
            ]
        elif any(w in q for w in ["date", "mfd", "pkd"]):
            sections.append(
                "**Statutory Date Requirements (G.S.R. 779(E)):**\n"
                "Per Rule 6(1)(d) as amended effective 01-12-2022, every package must clearly state the month and year "
                "of manufacture, packing, or import (e.g. `09/2026` or `Sep 2026`). Isolated date numbers lacking a "
                "statutory prefix (MFD/PKD) or future post-dated manufacturing dates strictly require `REVIEW`."
            )
            followups = [
                "Why is a post-dated MFD treated as a violation?",
                "Are 'Best Before' dates an acceptable substitute for MFD?",
            ]
        else:
            guidance = []
            for r in matched_rules:
                guidance.append(f"• **{r.title}** ({r.source}): {r.description} (Ref: *{r.gazetteReference}*)")
            sections.append("**Applicable Legal Metrology Provisions:**\n" + "\n".join(guidance))
            followups = [
                "Why was this label flagged for REVIEW?",
                "What physical verification is required for net quantity?",
                "How do I re-screen after human correction?",
            ]

        # Extracted declarations note
        decls = request.extracted_declarations or request.extracted_fields or {}
        if decls:
            summary_str = ", ".join([f"{k}: '{v}'" for k, v in decls.items() if v])
            if summary_str:
                sections.append(f"\n*Evaluated declarations from package:* {summary_str}")

        return InspectionAssistantResponse(
            answer="\n\n".join(sections),
            citations=citations,
            suggested_followups=followups,
            is_ai_generated=False,
            is_offline_fallback=True,
            provider_used="mock-statutory-engine",
            disclaimer=STATUTORY_DISCLAIMER,
            legal_disclaimer=STATUTORY_DISCLAIMER,
        )


class GeminiInspectionAiProvider(InspectionAiProvider):
    """
    Google Gemini 1.5 Flash Provider for Inspection Summary & Assistant.
    Conditioned strictly on statutory rules, gazette references, and deterministic guardrails.
    Gracefully falls back to MockInspectionAiProvider on any error, offline status, or missing API key.
    """

    def __init__(self, api_key: str, model: Optional[str] = None):
        self.api_key = api_key.strip()
        self.model = (model or os.getenv("GEMINI_MODEL") or "gemini-flash-lite-latest").strip()
        self.fallback = MockInspectionAiProvider()

    def _get_headers(self) -> Dict[str, str]:
        return {
            "Content-Type": "application/json",
            "x-goog-api-key": self.api_key,
        }

    def _get_url(self, model: str) -> str:
        return f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"

    async def _post_generate(self, client: httpx.AsyncClient, payload: dict) -> tuple[Optional[httpx.Response], str]:
        """Posts generateContent with primary model, cascading across available flash models on 404/429/503."""
        headers = self._get_headers()
        primary_model = self.model
        candidates = [primary_model, "gemini-flash-lite-latest", "gemini-3.5-flash-lite", "gemini-3.8-flash", "gemini-flash-latest"]
        seen = set()
        models_to_try = [m for m in candidates if m and not (m in seen or seen.add(m))]

        last_resp = None
        for cand in models_to_try:
            url = self._get_url(cand)
            resp = await client.post(url, json=payload, headers=headers)
            last_resp = resp
            if resp.status_code == 200:
                return resp, cand
            logger.warning("Gemini model %s returned status %d: %s", cand, resp.status_code, resp.text[:300])
            if resp.status_code not in (404, 429, 503):
                # Break on unrecoverable client errors (e.g. 400 Invalid Argument, 401/403 Permission Denied)
                break

        return last_resp, primary_model

    async def generate_summary(
        self, request: InspectionSummaryRequest
    ) -> InspectionSummaryResponse:
        if not self.api_key:
            return await self.fallback.generate_summary(request)

        system_instruction = (
            "You are the JAMEx Legal Metrology AI Inspection Specialist under the Ministry of Consumer Affairs, Government of India.\n"
            "Your role is to generate an authoritative, forensic inspection summary analyzing packaging declarations.\n"
            "MANDATORY GUARDRAILS:\n"
            "1. Compliance verdicts are strictly deterministic code based on the Legal Metrology (Packaged Commodities) Rules, 2011. "
            "You must NEVER override, alter, or ignore the provided verdict. If the verdict is 'REVIEW', you must never declare the package compliant or cleared.\n"
            "2. Ground all explanations strictly in Rule 6(1)(a)-(g) and official Gazette Notifications: G.S.R. 202(E), G.S.R. 629(E), G.S.R. 779(E), G.S.R. 359(E).\n"
            "3. If multiple packaging panels contain conflicting declarations (e.g. front panel vs back panel quantity or price), "
            "explicitly highlight the conflict in both key findings and evidence explanations.\n"
            "4. Return strictly valid JSON adhering to this schema:\n"
            "{\n"
            '  "overall_summary": "string",\n'
            '  "key_findings": ["string"],\n'
            '  "declarations_requiring_attention": ["string"],\n'
            '  "evidence_explanation": ["string"],\n'
            '  "applicable_rules": ["string"],\n'
            '  "recommended_next_steps": ["string"]\n'
            "}"
        )

        user_content = {
            "product_name": request.product_name,
            "deterministic_verdict": request.verdict,
            "extracted_declarations": request.extracted_declarations,
            "flagged_rules": request.flagged_rules,
            "potential_violations": request.potential_violations,
            "evidence_snippets": request.evidence_snippets,
        }

        payload = {
            "systemInstruction": {"parts": [{"text": system_instruction}]},
            "contents": [{"parts": [{"text": json.dumps(user_content)}]}],
            "generationConfig": {
                "responseMimeType": "application/json",
                "temperature": 0.1,
            },
        }

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp, used_model = await self._post_generate(client, payload)
                if not resp or resp.status_code != 200:
                    fb = await self.fallback.generate_summary(request)
                    fb.provider_used = "mock-statutory-engine (fallback)"
                    fb.is_ai_generated = False
                    return fb

                res_json = resp.json()
                raw_text = res_json["candidates"][0]["content"]["parts"][0]["text"]
                parsed = _parse_gemini_json(raw_text)

                # Guardrail: Never let LLM override REVIEW verdict
                overall_summary = parsed.get("overall_summary", "")
                if request.verdict.upper() == "REVIEW":
                    # Check if model hallucinated compliance
                    if any(c in overall_summary.lower() for c in ["verdict: pass", "verdict is pass", "marked as pass", "fully compliant and passed"]):
                        overall_summary = (
                            f"Automated statutory screening for '{request.product_name or 'Pre-Packaged Commodity'}' "
                            f"evaluated to REVIEW. Statutory declarations require officer verification under Legal Metrology Rules, 2011."
                        )

                return InspectionSummaryResponse(
                    overall_summary=overall_summary or "Statutory inspection summary generated.",
                    key_findings=parsed.get("key_findings", []),
                    declarations_requiring_attention=parsed.get("declarations_requiring_attention", []),
                    evidence_explanation=parsed.get("evidence_explanation", []),
                    applicable_rules=parsed.get("applicable_rules", []),
                    recommended_next_steps=parsed.get("recommended_next_steps", []),
                    is_ai_generated=True,
                    provider_used=f"gemini-{used_model}",
                    disclaimer=STATUTORY_DISCLAIMER,
                )
        except Exception as e:
            logger.warning("Gemini generate_summary error: %s", str(e))
            # Fallback seamlessly on any network error, format error, or rate limit
            fb = await self.fallback.generate_summary(request)
            fb.provider_used = "mock-statutory-engine (fallback)"
            fb.is_ai_generated = False
            return fb

    async def assistant_chat(
        self, request: InspectionAssistantRequest
    ) -> InspectionAssistantResponse:
        if not self.api_key:
            return await self.fallback.assistant_chat(request)

        # Check guardrail before network call
        q = request.query.lower().strip()
        if any(w in q for w in ["override", "make it pass", "mark pass", "force pass", "change verdict", "alter verdict"]):
            return await self.fallback.assistant_chat(request)

        system_instruction = (
            "You are the JAMEx Legal Metrology Compliance Assistant, advising inspectors and packaging teams "
            "on India's Legal Metrology (Packaged Commodities) Rules, 2011 and Legal Metrology Act, 2009.\n"
            "STRICT RULES:\n"
            "1. Ground all answers strictly in Rule 6(1)(a)-(g) and official Gazette Notifications: "
            "G.S.R. 202(E), G.S.R. 629(E), G.S.R. 779(E), and G.S.R. 359(E).\n"
            "2. Never hallucinate non-existent rules or grant legal clearance.\n"
            "3. If asked to override a verdict, state that compliance decisions are strictly deterministic code.\n"
            "4. Return valid JSON matching the schema:\n"
            '{"answer": "...", "citations": [{"rule_id": "...", "clause": "...", "title": "...", '
            '"gazette_reference": "...", "summary": "..."}], "suggested_followups": ["..."]}'
        )

        user_content = {
            "query": request.query,
            "product_name": request.product_name,
            "current_verdict": request.verdict,
            "extracted_declarations": request.extracted_declarations or request.extracted_fields,
            "flagged_rules": request.flagged_rules,
            "potential_violations": request.potential_violations,
            "evidence_snippets": request.evidence_snippets,
            "commodity": request.commodity,
        }

        payload = {
            "systemInstruction": {"parts": [{"text": system_instruction}]},
            "contents": [{"parts": [{"text": json.dumps(user_content)}]}],
            "generationConfig": {
                "responseMimeType": "application/json",
                "temperature": 0.1,
            },
        }

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp, used_model = await self._post_generate(client, payload)
                if not resp or resp.status_code != 200:
                    fb = await self.fallback.assistant_chat(request)
                    fb.provider_used = "mock-statutory-engine (fallback)"
                    fb.is_ai_generated = False
                    fb.is_offline_fallback = True
                    return fb

                res_json = resp.json()
                raw_text = res_json["candidates"][0]["content"]["parts"][0]["text"]
                parsed = _parse_gemini_json(raw_text)

                citations_raw = parsed.get("citations", [])
                citations = []
                for c in citations_raw:
                    if isinstance(c, dict):
                        citations.append(
                            GroundedCitation(
                                rule_id=c.get("rule_id", "LM-PCR-2011-R6"),
                                clause=c.get("clause", "Rule 6, PCR 2011"),
                                title=c.get("title", "Statutory Rule"),
                                gazette_reference=c.get("gazette_reference", "G.S.R. 779(E)"),
                                summary=c.get("summary", ""),
                            )
                        )

                if not citations:
                    fallback_res = await self.fallback.assistant_chat(request)
                    citations = fallback_res.citations

                return InspectionAssistantResponse(
                    answer=parsed.get("answer", "Analysis completed based on Legal Metrology provisions."),
                    citations=citations,
                    suggested_followups=parsed.get("suggested_followups", [
                        "What physical checks should the inspector conduct?",
                        "How do I correct an OCR misreading using Human Review?",
                    ]),
                    is_ai_generated=True,
                    is_offline_fallback=False,
                    provider_used=f"gemini-{used_model}",
                    disclaimer=STATUTORY_DISCLAIMER,
                    legal_disclaimer=STATUTORY_DISCLAIMER,
                )
        except Exception:
            fb = await self.fallback.assistant_chat(request)
            fb.provider_used = "mock-statutory-engine (fallback)"
            fb.is_ai_generated = False
            fb.is_offline_fallback = True
            return fb


def get_inspection_provider() -> InspectionAiProvider:
    """
    Factory function returning GeminiInspectionAiProvider if GEMINI_API_KEY is configured
    and COPILOT_PROVIDER != 'mock', otherwise returns MockInspectionAiProvider.
    """
    gemini_key = (os.getenv("GEMINI_API_KEY") or "").strip()
    provider_pref = (os.getenv("COPILOT_PROVIDER") or os.getenv("INSPECTION_AI_PROVIDER") or "").strip().lower()

    if gemini_key and provider_pref != "mock" and provider_pref != "local":
        model = os.getenv("GEMINI_MODEL", "gemini-flash-lite-latest")
        return GeminiInspectionAiProvider(api_key=gemini_key, model=model)

    return MockInspectionAiProvider()
