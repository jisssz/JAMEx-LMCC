from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, model_validator


class GroundedCitation(BaseModel):
    rule_id: str = Field(..., description="Unique statutory rule identifier (e.g. LM-PCR-2011-R6-1-DA)")
    clause: str = Field(..., description="Legal Metrology rule clause reference")
    title: str = Field(..., description="Statutory rule title")
    gazette_reference: str = Field(..., description="Official Gazette Notification reference number and date")
    summary: str = Field(..., description="Summary of statutory requirement and detection scope")


class PotentialViolationItem(BaseModel):
    rule_id: Optional[str] = None
    field: Optional[str] = None
    issue: Optional[str] = None
    severity: Optional[str] = "high"
    evidence: Optional[str] = None


class InspectionSummaryRequest(BaseModel):
    product_name: Optional[str] = Field(None, description="Trade name or brand name of pre-packaged commodity")
    verdict: str = Field(..., description="Deterministic verdict: PASS or REVIEW")
    extracted_declarations: Dict[str, Any] = Field(default_factory=dict, description="Extracted label declaration fields")
    flagged_rules: List[str] = Field(default_factory=list, description="List of rule IDs flagged by deterministic engine")
    potential_violations: List[Dict[str, Any]] = Field(default_factory=list, description="Structured violation records")
    evidence_snippets: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Raw OCR snippets, bounding boxes, or multi-panel text")


class InspectionSummaryResponse(BaseModel):
    overall_summary: str = Field(..., description="High-level narrative inspection summary")
    key_findings: List[str] = Field(default_factory=list, description="Detailed bullet points of detected findings")
    declarations_requiring_attention: List[str] = Field(default_factory=list, description="Fields or declarations flagged for inspection or missing")
    evidence_explanation: List[str] = Field(default_factory=list, description="Explanations linking evidence to statutory requirements")
    applicable_rules: List[str] = Field(default_factory=list, description="List of statutory rules and Gazette references applicable to findings")
    recommended_next_steps: List[str] = Field(default_factory=list, description="Actionable next steps for the field inspector")
    is_ai_generated: bool = Field(False, description="True if generated by external AI model, False if deterministic fallback")
    provider_used: str = Field(..., description="Model or engine identifier used to generate the summary")
    disclaimer: str = Field(
        default=(
            "Statutory Inspection Summary generated by Legal Metrology AI Assistant. This summary is intended "
            "for screening assistance under the Legal Metrology (Packaged Commodities) Rules, 2011. It does not replace "
            "statutory laboratory verification or formal legal compounding under the Legal Metrology Act, 2009. "
            "Compliance verdicts are strictly deterministic and cannot be modified by AI."
        ),
        description="Statutory legal and non-liability disclaimer",
    )


class InspectionAssistantRequest(BaseModel):
    query: str = Field(..., min_length=2, max_length=1000, description="Inspector query")
    product_name: Optional[str] = Field(None, description="Product or brand name")
    verdict: Optional[str] = Field(None, description="Current inspection verdict: PASS or REVIEW")
    extracted_declarations: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Current extracted label declarations")
    extracted_fields: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Alias for extracted_declarations")
    flagged_rules: Optional[List[str]] = Field(default_factory=list, description="IDs of rules flagged")
    potential_violations: Optional[List[Dict[str, Any]]] = Field(default_factory=list, description="Potential violations list")
    evidence_snippets: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Multi-panel evidence snippets")
    commodity: Optional[str] = Field(None, description="Optional commodity category")

    @model_validator(mode="before")
    @classmethod
    def sync_extracted_data(cls, values):
        if isinstance(values, dict):
            if "extracted_declarations" in values and ("extracted_fields" not in values or not values.get("extracted_fields")):
                values["extracted_fields"] = values["extracted_declarations"]
            elif "extracted_fields" in values and ("extracted_declarations" not in values or not values.get("extracted_declarations")):
                values["extracted_declarations"] = values["extracted_fields"]
        return values


class InspectionAssistantResponse(BaseModel):
    answer: str
    citations: List[GroundedCitation] = Field(default_factory=list)
    suggested_followups: List[str] = Field(default_factory=list)
    is_ai_generated: bool = False
    is_offline_fallback: bool = True
    provider_used: str = "mock-statutory-engine"
    disclaimer: str = (
        "Statutory Screening Copilot. Guidance is based on the Legal Metrology (Packaged Commodities) "
        "Rules, 2011. Does not constitute formal compounding authorization under the Legal Metrology Act, 2009."
    )
    legal_disclaimer: str = (
        "Statutory Screening Copilot. Guidance is based on the Legal Metrology (Packaged Commodities) "
        "Rules, 2011. Does not constitute formal compounding authorization under the Legal Metrology Act, 2009."
    )
